// Generates src/coach/preflopTable.js: the 169 starting hands ranked by preflop strength.
// Run with: node scripts/generate-preflop-table.mjs
//
// Strength blends three things (see docs/coach-algorithm.md):
//   1. equity vs one random hand            (raw hot/cold strength)
//   2. equity vs a strong range (top 20%)   (how well it holds up against hands that actually play back)
//   3. a small playability bonus            (suited / connected hands realize more equity postflop)
// Each class then gets its slice of the 1326 combos: [start, end) as fractions of all hands, which is
// what "top 15% of hands" style ranges are built from.
import { writeFileSync } from 'node:fs';
import { evaluate } from '../src/utils/handEvaluator.js';
import { COMBOS, CLASS_NAMES, CLASS_COMBOS } from '../src/coach/combos.js';
import { createRandom } from '../src/coach/random.js';

const SAMPLES = 30000;
const random = createRandom(20260929);

// One representative combo per class (equity doesn't depend on which suits, beyond suited/offsuit).
const representative = new Array(169);
for (const combo of COMBOS) if (!representative[combo.cls]) representative[combo.cls] = combo.cards;

// Hero equity for a class against villain combos drawn by `pickVillain`.
function equityOf(heroCards, pickVillain) {
  let score = 0;
  const deck = [];
  for (let c = 0; c < 52; c++) if (c !== heroCards[0] && c !== heroCards[1]) deck.push(c);
  for (let i = 0; i < SAMPLES; i++) {
    const villain = pickVillain(heroCards);
    const board = [];
    while (board.length < 5) {
      const card = deck[Math.floor(random() * deck.length)];
      if (card !== villain[0] && card !== villain[1] && !board.includes(card)) board.push(card);
    }
    const hero = evaluate([...heroCards, ...board]);
    const vill = evaluate([...villain, ...board]);
    score += hero > vill ? 1 : hero === vill ? 0.5 : 0;
  }
  return score / SAMPLES;
}

// Villain holds any two cards the hero doesn't.
const randomVillain = (hero) => {
  for (;;) {
    const a = Math.floor(random() * 52);
    const b = Math.floor(random() * 52);
    if (a !== b && !hero.includes(a) && !hero.includes(b)) return [a, b];
  }
};

console.log('Pass 1: equity vs a random hand...');
const eqRandom = representative.map((cards) => equityOf(cards, randomVillain));

// Top 20% of combos by raw equity: the "strong range" for pass 2.
const byRandom = [...Array(169).keys()].sort((a, b) => eqRandom[b] - eqRandom[a]);
const strongCombos = [];
let taken = 0;
for (const cls of byRandom) {
  if (taken >= 0.2 * 1326) break;
  taken += CLASS_COMBOS[cls];
  for (const combo of COMBOS) if (combo.cls === cls) strongCombos.push(combo.cards);
}
const strongVillain = (hero) => {
  for (;;) {
    const cards = strongCombos[Math.floor(random() * strongCombos.length)];
    if (!hero.includes(cards[0]) && !hero.includes(cards[1])) return cards;
  }
};

console.log('Pass 2: equity vs the top 20% of hands...');
const eqVsStrong = representative.map((cards) => equityOf(cards, strongVillain));

// Playability: suited and connected hands make more straights/flushes and play better postflop.
function playability(cls) {
  const row = Math.floor(cls / 13);
  const col = cls % 13;
  if (row === col) return 0.015; // pairs: set value
  const suited = row < col;
  const gap = Math.abs(row - col) - 1;
  const connected = gap === 0 ? 0.012 : gap === 1 ? 0.008 : gap === 2 ? 0.004 : 0;
  return (suited ? 0.022 : 0) + connected;
}

const classes = [...Array(169).keys()].map((cls) => ({
  cls,
  name: CLASS_NAMES[cls],
  combos: CLASS_COMBOS[cls],
  eqRandom: eqRandom[cls],
  eqVsStrong: eqVsStrong[cls],
  score: 0.45 * eqRandom[cls] + 0.55 * eqVsStrong[cls] + playability(cls),
}));
classes.sort((a, b) => b.score - a.score);

// Cumulative slice of all combos for each class.
let cumulative = 0;
for (const entry of classes) {
  entry.start = cumulative / 1326;
  cumulative += entry.combos;
  entry.end = cumulative / 1326;
}

const round = (n) => Math.round(n * 10000) / 10000;
const rows = classes
  .map(
    (c) =>
      `  { cls: ${c.cls}, name: '${c.name}', combos: ${c.combos}, eqRandom: ${round(c.eqRandom)}, eqVsStrong: ${round(c.eqVsStrong)}, score: ${round(c.score)}, start: ${round(c.start)}, end: ${round(c.end)} },`
  )
  .join('\n');

const output = `// Generated by scripts/generate-preflop-table.mjs (${SAMPLES} samples per matchup). Do not edit by hand.
// The 169 starting hands from strongest to weakest. start/end = the hand's slice of all 1326 combos,
// e.g. a hand with end 0.15 is inside a "top 15%" range.
export const PREFLOP_TABLE = [
${rows}
];

// Lookup by grid cell (see coach/combos.js).
export const PREFLOP_BY_CLASS = new Array(169);
for (const entry of PREFLOP_TABLE) PREFLOP_BY_CLASS[entry.cls] = entry;
`;

writeFileSync(new URL('../src/coach/preflopTable.js', import.meta.url), output);
console.log('Top 25:', classes.slice(0, 25).map((c) => c.name).join(' '));
console.log('Around 15%:', classes.filter((c) => c.start > 0.13 && c.start < 0.17).map((c) => c.name).join(' '));
console.log('Around 30%:', classes.filter((c) => c.start > 0.28 && c.start < 0.32).map((c) => c.name).join(' '));
console.log('Around 50%:', classes.filter((c) => c.start > 0.48 && c.start < 0.52).map((c) => c.name).join(' '));
console.log('Bottom 10:', classes.slice(-10).map((c) => c.name).join(' '));
